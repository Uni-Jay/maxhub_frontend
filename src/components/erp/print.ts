import type { Brand, Payment } from '@services/erpService';
import { money } from '@services/erpService';
import { BRAND_LOGOS } from '@hooks/useErp';

const esc = (s: any) => String(s ?? '').replace(/[&<>"']/g, (c) => ({ '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;', "'": '&#39;' }[c]!));

function abs(url?: string) {
  if (!url) return '';
  return /^https?:|^data:/.test(url) ? url : `${window.location.origin}${url.startsWith('/') ? '' : '/'}${url}`;
}

/** Opens a print window with the brand letterhead around the given HTML. */
export function printWithLetterhead(title: string, bodyHtml: string, brand?: Partial<Brand> | null, opts: { footer?: string } = {}) {
  const color = brand?.primaryColor || '#4f46e5';
  const logo = abs(brand?.logoUrl || (brand?.code ? BRAND_LOGOS[brand.code] : ''));
  const w = window.open('', '_blank', 'width=900,height=1000');
  if (!w) { alert('Please allow pop-ups for this site to print.'); return; }
  w.document.write(`<!doctype html><html><head><meta charset="utf-8"><title>${esc(title)}</title>
<style>
  *{box-sizing:border-box} body{font-family:'Segoe UI',Arial,sans-serif;color:#1f2937;margin:0;padding:32px 40px;font-size:13px;line-height:1.55}
  .lh{display:flex;align-items:center;justify-content:space-between;border-bottom:3px solid ${color};padding-bottom:14px;margin-bottom:22px;gap:16px}
  .lh img{max-height:70px;max-width:260px;object-fit:contain}
  .lh .info{text-align:right;font-size:11px;color:#4b5563}
  .lh .name{font-size:18px;font-weight:700;color:${color}}
  h1{font-size:20px;margin:0 0 4px;color:${color}} h2{font-size:16px;color:${color}} h3{font-size:14px;margin:16px 0 6px}
  table{width:100%;border-collapse:collapse;margin:10px 0} th,td{padding:7px 9px;border:1px solid #e5e7eb;text-align:left;vertical-align:top}
  th{background:#f3f4f6;font-weight:600} .muted{color:#6b7280} .right{text-align:right} .big{font-size:18px;font-weight:700}
  .badge{display:inline-block;padding:2px 10px;border-radius:999px;background:${color};color:#fff;font-size:11px}
  .void{color:#b91c1c;border:2px solid #b91c1c;display:inline-block;padding:4px 12px;font-weight:700;transform:rotate(-4deg);margin:8px 0}
  .sig{margin-top:28px;display:flex;gap:40px} .sig div{flex:1} .sig img{max-height:80px;display:block;margin-bottom:4px}
  .line{border-top:1px solid #9ca3af;padding-top:4px;font-size:11px;color:#6b7280}
  .foot{margin-top:30px;border-top:1px solid #e5e7eb;padding-top:10px;font-size:10px;color:#6b7280;text-align:center}
  @media print{body{padding:16px 22px} .noprint{display:none}}
</style></head><body>
<div class="lh">${logo ? `<img src="${esc(logo)}" alt="">` : `<div class="name">${esc(brand?.displayName || 'MaxHub')}</div>`}
  <div class="info"><div class="name">${esc(brand?.displayName || 'MaxHub')}</div>${esc(brand?.tagline || '')}<br>${esc(brand?.address || '')}<br>${[brand?.phone, brand?.email, brand?.website].filter(Boolean).map(esc).join(' · ')}</div></div>
${bodyHtml}
<div class="foot">${esc(opts.footer || brand?.footerNote || `Generated by MaxHub ERP on ${new Date().toLocaleString()}`)}</div>
<div class="noprint" style="text-align:center;margin-top:20px"><button onclick="window.print()" style="padding:10px 22px;background:${color};color:#fff;border:0;border-radius:8px;font-size:14px;cursor:pointer">Print / Save as PDF</button></div>
<script>window.onload=function(){setTimeout(function(){window.print()},400)}</script>
</body></html>`);
  w.document.close();
}

export function printReceipt(p: Payment, brand?: Partial<Brand> | null, balance?: { totalDue: number; paidToDate: number; outstanding: number } | null) {
  const items = Array.isArray(p.items) && p.items.length ? p.items : [{ description: p.description, qty: 1, amount: p.amount }];
  const rows = items.map((i: any) => `<tr><td>${esc(i.description || i.name)}</td><td class="right">${esc(i.qty ?? 1)}</td><td class="right">${money(i.amount ?? (Number(i.qty || 1) * Number(i.unitPrice || 0)), p.currency)}</td></tr>`).join('');
  printWithLetterhead(`Receipt ${p.receiptNo}`, `
<div style="display:flex;justify-content:space-between;align-items:flex-start">
  <div><h1>PAYMENT RECEIPT</h1><div class="muted">Receipt No: <strong>${esc(p.receiptNo)}</strong></div>
  <div class="muted">Date: ${new Date(p.paidAt).toLocaleString()}</div>${p.relatedCode ? `<div class="muted">Reference: ${esc(p.relatedCode)}</div>` : ''}</div>
  <div class="right"><span class="badge">${esc(p.status)}</span></div></div>
${p.status === 'Voided' ? `<div class="void">VOID — ${esc(p.voidReason || '')}</div>` : ''}
<h3>Received from</h3><div><strong>${esc(p.customerName)}</strong><br>${[p.customerPhone, p.customerEmail].filter(Boolean).map(esc).join(' · ')}</div>
<table><tr><th>Description</th><th class="right" style="width:70px">Qty</th><th class="right" style="width:160px">Amount</th></tr>${rows}
<tr><td colspan="2" class="right"><strong>Total paid</strong></td><td class="right big">${money(p.amount, p.currency)}</td></tr></table>
<table><tr><th style="width:30%">Payment method</th><td>${esc(p.method)}${p.reference ? ` — ${esc(p.reference)}` : ''}</td></tr>
${balance ? `<tr><th>Total due</th><td>${money(balance.totalDue, p.currency)}</td></tr><tr><th>Paid to date</th><td>${money(balance.paidToDate, p.currency)}</td></tr><tr><th>Outstanding balance</th><td><strong>${money(balance.outstanding, p.currency)}</strong></td></tr>` : ''}
<tr><th>Received by</th><td>${esc(p.receivedByName || '')}</td></tr></table>
${brand?.bankDetails ? `<h3>Bank details</h3><div style="white-space:pre-line">${esc(brand.bankDetails)}</div>` : ''}
<div class="sig"><div><div class="line">Customer signature</div></div><div><div class="line">For ${esc(brand?.displayName || 'MaxHub')}</div></div></div>`, brand, { footer: 'Thank you for your business. This receipt was generated electronically.' });
}

export function printSignedDocument(doc: any, brand?: Partial<Brand> | null) {
  const signed = ['Signed', 'Acknowledged'].includes(doc.status);
  printWithLetterhead(`${doc.title} — ${doc.code || ''}`, `
<div class="muted" style="margin-bottom:8px">Document ${esc(doc.code || '')} · ${esc(doc.category || '')} · Status: <strong>${esc(doc.status)}</strong></div>
<div>${doc.renderedBody || doc.body || (doc.fileUrl ? `<p>See attached file: <a href="${esc(doc.fileUrl)}">${esc(doc.fileUrl)}</a></p>` : '')}</div>
${signed ? `<div class="sig"><div>${doc.signatureImage ? `<img src="${esc(doc.signatureImage)}" alt="signature">` : ''}<div class="line">${esc(doc.signerName)} — ${doc.requiresSignature ? 'signed' : 'acknowledged'} ${doc.signedAt ? new Date(doc.signedAt).toLocaleString() : ''}</div></div>
<div><div class="line">For ${esc(brand?.displayName || '')}</div></div></div>
<p class="muted" style="font-size:10px;margin-top:14px">Electronic record: signed from IP ${esc(doc.signerIp || '—')}. Document fingerprint (SHA-256): ${esc(doc.contentHash || '—')}</p>` : ''}
${doc.status === 'Declined' ? `<p><strong>Declined</strong>${doc.declineReason ? `: ${esc(doc.declineReason)}` : ''}</p>` : ''}`, brand);
}

/** Generic printable summary of any record: label/value pairs plus optional timeline. */
export function printRecord(title: string, fields: [string, any][], brand?: Partial<Brand> | null, activities?: { content: string; createdAt: string; createdByName?: string; kind: string }[], extraHtml = '') {
  const rows = fields.filter(([, v]) => v !== undefined && v !== null && v !== '').map(([k, v]) => `<tr><th style="width:32%">${esc(k)}</th><td>${esc(v)}</td></tr>`).join('');
  const tl = activities?.length ? `<h3>History</h3><table><tr><th style="width:170px">When</th><th style="width:120px">Type</th><th>Details</th></tr>${activities.map((a) => `<tr><td>${new Date(a.createdAt).toLocaleString()}</td><td>${esc(a.kind)}</td><td>${esc(a.content)}${a.createdByName ? ` <span class="muted">— ${esc(a.createdByName)}</span>` : ''}</td></tr>`).join('')}</table>` : '';
  printWithLetterhead(title, `<h1>${esc(title)}</h1><table>${rows}</table>${extraHtml}${tl}`, brand);
}

export function printTable(title: string, headers: string[], rows: any[][], brand?: Partial<Brand> | null, intro = '') {
  printWithLetterhead(title, `<h1>${esc(title)}</h1>${intro}<table><tr>${headers.map((h) => `<th>${esc(h)}</th>`).join('')}</tr>${rows.map((r) => `<tr>${r.map((c) => `<td>${esc(c)}</td>`).join('')}</tr>`).join('')}</table>`, brand);
}
